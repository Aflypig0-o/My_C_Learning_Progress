#include <stdio.h>
#include <string.h>
#include <ctype.h>
#include <stdlib.h>
#include "infix.h"
#include "tokenize.h"
#include "charstack.h"

/*
 * ============================================================
 *  output_token —— 向输出数组写入一个 Token 的辅助函数
 * ============================================================
 *  封装了"检查容量 → 写入 → 计数+1"的重复逻辑。
 *
 *  参数：
 *      out       - 输出数组
 *      out_count_local - 当前已写入个数（指针，函数内部会 +1）
 *      max_out   - 数组容量上限
 *      tok       - 要写入的 Token
 *
 *  返回：
 *      true  - 写入成功
 *      false - 数组已满，写入失败
 */
static bool output_token(Token *out, int *out_count_local, int max_out, Token tok)
{
    if (*out_count_local >= max_out)
    {
        return false;
    }
    out[*out_count_local] = tok;
    (*out_count_local)++;
    return true;
}

/*
 * ============================================================
 *  infix_to_postfix —— 调度场算法（Shunting-Yard Algorithm）
 * ============================================================
 *
 *  功能：把中缀表达式（人类习惯的写法）转成后缀表达式（机器好算的写法）
 *
 *  举例：
 *      中缀：3 + 4 * 2
 *      后缀：3 4 2 * +
 *
 *      中缀：(3 + 4) * 2
 *      后缀：3 4 + 2 *
 *
 *  核心思想：
 *      用一个"运算符栈"来临时存放还没到输出时机的运算符。
 *      数字直接输出，运算符看优先级决定"现在输出"还是"先压栈等后面"。
 *      左括号是"屏障"，挡住栈里的运算符不被弹出。
 *
 *  参数：
 *      in      - 输入的中缀表达式 Token 数组（已经 tokenize 好的）
 *      count   - in 数组里有效 Token 的个数
 *      out     - 输出的后缀表达式 Token 数组（调用者提前分配好空间）
 *      max_out - out 数组最多能容纳多少个 Token（防止越界）
 *
 *  返回：
 *      true  - 转换成功，out 里存好了后缀表达式
 *      false - 出错（括号不匹配、输出数组太小等）
 */
bool infix_to_postfix(Token *in, int count, Token *out, int max_out,int *out_count)
{
    // 参数合法性检查：指针不能为空
    if (in == NULL || out == NULL)
    {
        return false;
    }

    // 创建一个字符栈，专门用来临时存放运算符和左括号
    // 可以理解为：这是一个"等待区"，运算符在这里排队，
    // 等到"时机成熟"（遇到更低优先级的运算符或右括号）才输出
    Charstack cs;
    charstack_init(&cs);

    // out_count_local：记录 out 数组里已经写了多少个 Token
    // 相当于 out 数组的"当前长度"
    int out_count_local = 0;

    // 从左到右，逐个扫描输入 Token
    for (int i = 0; i < count; ++i)
    {
        // ================================================================
                // 情况1：当前 Token 是数字（TOKEN_NUMBER）
        // ================================================================
        // 数字没有优先级的问题，不管前面是什么，直接输出就行。
        // 因为后缀表达式里数字的位置就是它在中缀表达式里的位置。
        if (in[i].type == TOKEN_NUMBER)
        {
            if (!output_token(out, &out_count_local, max_out, in[i]))
            {
                return false;
            }
        }

        // ================================================================
        // 情况2：当前 Token 是运算符（TOKEN_OP）
        // ================================================================
        // 这是整个算法最核心的部分。
        //
        // 规则：
        //   把栈里"优先级 >= 当前运算符"的运算符全部弹出来输出，
        //   然后把当前运算符压栈。
        //
        // 为什么？
        //   因为优先级高的运算符应该先算（先出现在后缀表达式里）。
        //   比如 3 + 4 * 2，扫到 * 时，栈里是 +。
        //   + 优先级(1) < * 优先级(2)，所以 + 不弹，* 压栈。
        //   最后弹栈时 * 先出，+ 后出 → 3 4 2 * +（正确）
        //
        //   比如 3 * 4 + 2，扫到 + 时，栈里是 *。
        //   * 优先级(2) >= + 优先级(1)，所以 * 弹出来输出。
        //   然后 + 压栈。→ 3 4 * + 2（正确）
        //
        // 左括号的作用：
        //   左括号是"屏障"，栈顶是左括号时停止弹出。
        //   因为括号里的运算符应该和括号里的数字一起算，
        //   不应该被括号外面的运算符"抢走"。
        else if (in[i].type == TOKEN_OP)
        {
            char top; // 用来接收栈顶字符的临时变量

            // while 循环条件（四个条件全部满足才继续弹）：
            //
            //   ① !charstack_is_empty(&cs)
            //      栈不为空。空了就没东西可弹了。
            //      （这个判断也避免了 peek 在空栈上打印错误信息）
            //
            //   ② charstack_peek(&cs, &top)
            //      把栈顶字符取到 top 里。
            //      返回 true 表示取成功了。
            //      （和①重复，但保险起见留着）
            //
            //   ③ top != '('
            //      栈顶不是左括号。左括号是屏障，不能弹。
            //      比如 (3 + 4) * 2，扫到 * 时栈顶是 (，不能弹 (。
            //
            //   ④ priority(top) >= priority(in[i].op)
            //      栈顶运算符的优先级 >= 当前运算符的优先级。
            //      只有"更急"的运算符才需要先输出。
            //
            // 任何一个条件不满足，就停止弹出，把当前运算符压栈。
            while (!charstack_is_empty(&cs) && charstack_peek(&cs, &top) && top != '(' && priority(top) >= priority(in[i].op))
            {
                charstack_pop(&cs, &top);

                Token op_tok = { TOKEN_OP, 0.0, top };
                if (!output_token(out, &out_count_local, max_out, op_tok))
                {
                    return false;
                }
            }

            // 当前运算符压栈，等后面"时机成熟"再输出
            // 比如扫到 * 时 + 在栈里但优先级低，* 就先等着
            charstack_push(&cs, in[i].op);
        }

        // ================================================================
        // 情况3：当前 Token 是左括号（TOKEN_LPAREN）
        // ================================================================
        // 左括号直接压栈，不做任何输出。
        //
        // 它的作用是当"屏障"：
        //   后面遇到运算符时，while 循环看到栈顶是 ( 就停了，
        //   不会把括号里面的运算符弹出来。
        //
        // 举例：(3 + 4) * 2
        //   扫到 ( → 压栈
        //   扫到 + → 栈顶是 (，不弹，+ 压栈
        //   扫到 ) → 弹出 + 输出，弹出 ( 丢弃
        //   扫到 * → 栈空，* 压栈
        else if (in[i].type == TOKEN_LPAREN)
        {
            charstack_push(&cs, in[i].op);
        }

        // ================================================================
        // 情况4：当前 Token 是右括号（TOKEN_RPAREN）
        // ================================================================
        // 遇到右括号，说明括号里的表达式结束了。
        // 把栈里从右括号往上的运算符全部弹出来输出，
        // 直到碰到左括号为止（左括号弹掉但不输出）。
        //
        // 举例：(3 + 4) * 2
        //   扫到 ) 时栈里是 [(, +]
        //   弹出 + → 输出
        //   碰到 ( → 停，弹出 ( 丢弃
        //   结果：3 4 +
        else if (in[i].type == TOKEN_RPAREN)
        {
            char top;

            // 不断弹出栈顶并输出，直到碰到左括号
            // 条件：peek 成功（栈不空）且栈顶不是左括号
            while (charstack_peek(&cs, &top) && top != '(')
            {
                charstack_pop(&cs, &top);

                Token op_tok = { TOKEN_OP, 0.0, top };
                if (!output_token(out, &out_count_local, max_out, op_tok))
                {
                    return false;
                }
            }

            // 弹出左括号本身（不输出，它只是标记"这里开始"）
            // 注意：如果栈空了说明括号不匹配，但 charstack_pop 会报错
            // 严格来说应该先判断栈是否为空，这里简化处理
            charstack_pop(&cs, &top);
        }
    }

    // ================================================================
    // 扫描结束：把栈里剩下的运算符全部弹出来输出
    // ================================================================
    // 为什么？
    //   有些运算符优先级低，一直没被弹出来，还留在栈里。
    //   比如 3 + 4 * 2，扫完后栈里是 [+ *]，需要按顺序弹出来    
    //   弹出顺序：* 先出（栈顶），+ 后出 → 3 4 2 * +
    //
    // 注意：如果这里弹出来的是左括号，说明括号不匹配，报错。
    char top;
    while (!charstack_is_empty(&cs))
    {
        // 弹出栈顶
        charstack_pop(&cs, &top);

        // 如果弹出来的是左括号，说明有左括号没有对应的右括号
        // 表达式不合法
        if (top == '(')
        {
            return false;
        }

        Token op_tok = { TOKEN_OP, 0.0, top };
        if (!output_token(out, &out_count_local, max_out, op_tok))
        {
            return false;
        }
    }
    *out_count = out_count_local;
    // 全部处理完毕，返回成功
    return true;
}